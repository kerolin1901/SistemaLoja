/* ================================================================
   SISTEMA DA LOJA — FORNECEDORES E OBSERVAÇÕES DE PRODUTOS
   Execute uma vez no SQL Editor do Supabase.

   - Cria fornecedores por loja, com RLS para administrador ativo.
   - Preserva o campo texto produtos.fornecedor já utilizado nas telas.
   - Migra os nomes de fornecedores já escritos nos produtos para a nova tabela.
   - Vincula os produtos existentes pelo fornecedor_id.
   - Adiciona produtos.observacoes.
   ================================================================ */

BEGIN;

DO $preflight$
BEGIN
    IF to_regclass('public.lojas') IS NULL
       OR to_regclass('public.perfis') IS NULL
       OR to_regclass('public.produtos') IS NULL THEN
        RAISE EXCEPTION 'Migração interrompida: as tabelas lojas, perfis e produtos precisam existir.';
    END IF;
    IF to_regprocedure('public.usuario_e_admin()') IS NULL
       OR to_regprocedure('public.usuario_loja_id()') IS NULL THEN
        RAISE EXCEPTION 'Migração interrompida: as funções usuario_e_admin() e usuario_loja_id() precisam existir.';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'produtos' AND column_name = 'fornecedor'
    ) THEN
        RAISE EXCEPTION 'Migração interrompida: a coluna produtos.fornecedor não foi encontrada.';
    END IF;
END;
$preflight$;

CREATE TABLE IF NOT EXISTS public.fornecedores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id uuid NOT NULL REFERENCES public.lojas(id) ON DELETE CASCADE,
    nome text NOT NULL CHECK (length(btrim(nome)) BETWEEN 1 AND 120),
    cnpj text,
    contato text,
    telefone text,
    email text,
    endereco text,
    observacoes text,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fornecedores_id_loja_unique UNIQUE (id, loja_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_fornecedores_loja_nome_normalizado
    ON public.fornecedores (loja_id, lower(btrim(nome)));
CREATE INDEX IF NOT EXISTS idx_fornecedores_loja_ativos_nome
    ON public.fornecedores (loja_id, ativo, nome);

ALTER TABLE public.produtos
    ADD COLUMN IF NOT EXISTS fornecedor_id bigint;
ALTER TABLE public.produtos
    ADD COLUMN IF NOT EXISTS observacoes text;

DO $fk$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'produtos_fornecedor_loja_fk'
          AND conrelid = 'public.produtos'::regclass
    ) THEN
        ALTER TABLE public.produtos
            ADD CONSTRAINT produtos_fornecedor_loja_fk
            FOREIGN KEY (fornecedor_id, loja_id)
            REFERENCES public.fornecedores (id, loja_id)
            ON DELETE RESTRICT;
    END IF;
END;
$fk$;

/* Migra os nomes já digitados no campo antigo para o cadastro estruturado. */
INSERT INTO public.fornecedores (loja_id, nome)
SELECT p.loja_id, min(btrim(p.fornecedor)) AS nome
FROM public.produtos AS p
WHERE p.loja_id IS NOT NULL
  AND nullif(btrim(p.fornecedor), '') IS NOT NULL
GROUP BY p.loja_id, lower(btrim(p.fornecedor))
ON CONFLICT DO NOTHING;

/* Vincula cada produto ao fornecedor migrado, sem apagar o campo texto legado. */
UPDATE public.produtos AS p
SET fornecedor_id = f.id
FROM public.fornecedores AS f
WHERE p.fornecedor_id IS NULL
  AND p.loja_id = f.loja_id
  AND nullif(btrim(p.fornecedor), '') IS NOT NULL
  AND lower(btrim(p.fornecedor)) = lower(btrim(f.nome));

ALTER TABLE public.fornecedores ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS fornecedores_admin_select ON public.fornecedores;
CREATE POLICY fornecedores_admin_select
    ON public.fornecedores
    FOR SELECT TO authenticated
    USING (loja_id = public.usuario_loja_id() AND public.usuario_e_admin());

DROP POLICY IF EXISTS fornecedores_admin_insert ON public.fornecedores;
CREATE POLICY fornecedores_admin_insert
    ON public.fornecedores
    FOR INSERT TO authenticated
    WITH CHECK (loja_id = public.usuario_loja_id() AND public.usuario_e_admin());

DROP POLICY IF EXISTS fornecedores_admin_update ON public.fornecedores;
CREATE POLICY fornecedores_admin_update
    ON public.fornecedores
    FOR UPDATE TO authenticated
    USING (loja_id = public.usuario_loja_id() AND public.usuario_e_admin())
    WITH CHECK (loja_id = public.usuario_loja_id() AND public.usuario_e_admin());

GRANT SELECT, INSERT, UPDATE ON public.fornecedores TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.fornecedores_id_seq TO authenticated;

COMMIT;

